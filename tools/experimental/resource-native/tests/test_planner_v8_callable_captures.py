def fixture(kind='pending-step'):
    raw=c.fixture();bonus=raw['body']['body'];rec=bonus['body']
    typ=II
    if kind=='pending-step':
        value=f.lam(33,f.I,f.app(f.use(1,f.I),f.add(f.var(33),f.var(30))))
        contribution=f.app(f.var(31),f.lit(0))
    elif kind=='view-alias':
        value=f.use(1,f.I)
        contribution=f.app(f.var(31),f.var(30))
    elif kind=='closed':
        value=f.lam(33,f.I,f.add(f.var(33),f.lit(21)))
        contribution=f.app(f.var(31),f.lit(0))
    elif kind=='nested':
        typ=f.arr(II,f.arr(f.B,f.I))
        value=f.lam(33,II,f.lam(34,f.B,f.app(f.var(33),f.lit(21))))
        contribution=f.app(f.app(f.var(31),f.lam(35,f.I,f.var(35))),f.boolean())
    elif kind=='nominal':
        typ=f.arr(c.SELF,f.I)
        value=f.lam(33,c.SELF,f.lit(21))
        contribution=f.app(f.var(31),f.var(12))
    else:
        raise AssertionError('unknown test fixture')
    step=f.app(f.lam(32,typ,f.var(32)),value)
    arm=rec['bindings'][0]['value']['argument']['body']['body']['alternatives'][1]
    arm['body']['function']['argument']=contribution
    bonus['body']=f.let(31,step,rec)
    return raw


def canonical(value):
    return json.dumps(value,sort_keys=True,separators=(',',':'),ensure_ascii=False).encode()


def allocation_for_binder(result, raw, ident):
    path,node=next((p,n) for p,n in transport._walk(raw) if n['tag']=='let' and n['name']['id']==ident)
    source=planner.address(path+('value',))
    row,=[x for x in result['binding']['source_map']['allocation_map'] if x['source']==source]
    return instruction(result['program'],row['instruction'])


class CallableCapturePlannerTests(unittest.TestCase):
    def checked(self,raw,groups=False):
        before=copy.deepcopy(raw);result=planner.plan_fragment(raw,data_groups=groups)
        self.assertEqual(raw,before)
        self.assertFalse(result['binding']['source_admitted'])
        self.assertFalse(result['binding']['ordinary_K_checked'])
        check_resources(result['program'])
        return result

    def test_pending_ordinary_and_instance_alias_both_modes(self):
        for kind in ('pending-step','view-alias'):
            for groups in (False,True):
                with self.subTest(kind=kind,groups=groups):
                    raw=fixture(kind);result=self.checked(raw,groups)
                    knot,carrier,closure=c.target(result);captures=knot['captures']
                    self.assertEqual(captures['policy'],POLICY)
                    self.assertEqual(len(captures['callables']),1)
                    self.assertEqual(captures['callables'][0]['type'],II)
                    self.assertEqual(len(captures['scalars']),int(kind=='view-alias'))
                    self.assertEqual(captures['views'],[])
                    self.assertEqual(carrier['view_captures'],[])
                    owner=allocation_for_binder(result,raw,31)
                    capture,=[x for x in carrier['mono_captures'] if x['binder']==31]
                    self.assertEqual(owner['op'],'application')
                    self.assertEqual(closure['captures'][capture['capture']],owner['out'])
                    self.assertIsNone(carrier['type_scope'])
                    program=result['program']
                    self.assertEqual(sum(x['op']=='instantiate' for x in c.all_ops(program)),2)
                    self.assertEqual(json.loads(emit_runtime(program).canonical_ir_json),program)

    def test_callable_owner_support_is_preserved_without_eager_force(self):
        for kind in ('pending-step','view-alias','closed'):
            for groups in (False,True):
                result=self.checked(fixture(kind),groups);knot,carrier,_=c.target(result)
                capture,=[x for x in carrier['mono_captures'] if x['binder']==31]
                self.assertEqual(capture['relation'],'below' if groups and kind!='pending-step' else 'down')
                end=knot['fill']['segments'][0]
                self.assertFalse(any(x['op']=='force' for x in result['program']['entry'][:end]))
                rhs,=[x for x in result['binding']['source_map']['allocation_map'] if x['source']==knot['rhs']]
                self.assertEqual(instruction(result['program'],rhs['instruction'])['op'],'application')
                self.assertEqual(instruction(result['program'],knot['fill'])['value'],knot['rhs_owner'])

    def test_nested_argument_and_result_arrows_retain_full_contract(self):
        raw=fixture('nested')
        for groups in (False,True):
            result=self.checked(raw,groups);knot,carrier,_=c.target(result)
            expected=f.arr(II,f.arr(f.B,f.I))
            self.assertEqual(knot['captures']['callables'][0]['type'],expected)
            capture,=[x for x in carrier['mono_captures'] if x['binder']==31]
            row=result['program']['types'][capture['layout'][1:]]
            self.assertEqual(row['protocol'],'repeat');self.assertEqual(row['result_identity'],'unknown')
            self.assertEqual(result['program']['types'][row['argument']]['tag'],'arrow')
            self.assertEqual(result['program']['types'][row['result']]['tag'],'arrow')
            self.assertEqual(json.loads(emit_runtime(result['program']).canonical_ir_json),result['program'])

    def test_equal_callable_types_do_not_merge_distinct_owners(self):
        raw=fixture('closed');step=raw['body']['body']['body'];rec=step['body']
        second=f.app(f.lam(35,II,f.var(35)),f.lam(36,f.I,f.add(f.var(36),f.lit(1))))
        step['body']=f.let(34,second,rec)
        arm=rec['bindings'][0]['value']['argument']['body']['body']['alternatives'][1]
        arm['body']['function']['argument']=f.add(f.app(f.var(31),f.lit(0)),f.app(f.var(34),f.lit(0)))
        result=self.checked(raw);knot,carrier,closure=c.target(result)
        self.assertEqual([x['binding']['id'] for x in knot['captures']['callables']],[31,34])
        a,b=[x for x in carrier['mono_captures'] if x['binder'] in (31,34)]
        self.assertEqual(a['layout'],b['layout'])
        self.assertNotEqual(closure['captures'][a['capture']],closure['captures'][b['capture']])

    def test_foreign_nominal_callable_owner_still_rejected(self):
        # Published closed nominal arrows are admitted by the newer policy;
        # an undeclared nominal atom is still not an ordinary callable type.
        raw=fixture('nominal');step=raw['body']['body']['body']['value']
        foreign=f.nominal('Foreign')
        step['function']['parameter_type']=f.arr(foreign,f.I)
        step['argument']['parameter_type']=foreign
        with self.assertRaises(transport.SharedTransportError) as caught:planner.plan_fragment(raw)
        self.assertEqual(caught.exception.code,'TYPE')

    def test_callable_inventory_and_full_type_forgeries_rejected(self):
        raw=fixture();fragment=transport.derive_shared_fragment(raw)
        changes=[lambda r:r['captures'].pop('callables'),
            lambda r:r['captures']['callables'].clear(),
            lambda r:r['captures'].update(policy='closed-scalar-shared-view-captures/1'),
            lambda r:r['captures']['callables'][0].update(type=f.arr(f.B,f.I)),
            lambda r:r['captures']['callables'][0].update(type=f.arr(f.I,f.B)),
            lambda r:r['captures']['callables'].append(copy.deepcopy(r['captures']['callables'][0])),
            lambda r:r['captures']['scalars'].append(copy.deepcopy(r['captures']['callables'][0]))]
        for change in changes:
            bad=copy.deepcopy(fragment);change(bad['recursion']['bindings'][0])
            with self.assertRaises(transport.SharedTransportError):planner.plan_fragment(raw,fragment=bad)
            with self.assertRaises(planner.PlanningError):planner.Planner(bad).finish()

    def test_internal_callable_guard_rejects_nonclosed_structures(self):
        fragment=transport.derive_shared_fragment(fixture())
        badtypes=[f.I,f.ty(99),{'tag':'forall','id':99,'bound':{'tag':'bottom'},'body':II},
                  f.arr(c.SELF,f.I),f.arr(f.I,f.arr(f.B,c.SELF))]
        for typ in badtypes:
            bad=copy.deepcopy(fragment);bad['recursion']['bindings'][0]['captures']['callables'][0]['type']=typ
            with self.assertRaises(planner.PlanningError):planner.Planner(bad).finish()

    def test_actual_capture_count_includes_callables_and_self(self):
        # Isolated planner-helper guard, not claimed source/compiler evidence.
        fragment=transport.derive_shared_fragment(fixture())
        original=fragment['recursion']['bindings'][0]
        for count in (63,64):
            evidence=copy.deepcopy(original);ids=list(range(200,200+count))
            evidence['free_term_bindings']=ids
            evidence['captures']={'policy':POLICY,'scalars':[],'views':[],
                'callables':[{'binding':f.name(i),'type':II,'occurrences':[]} for i in ids]}
            engine=planner.Planner(fragment)
            typ=planner.arrow(planner.SCALARS['Int'],planner.SCALARS['Int'])
            owners={i:planner.Reference('owner'+str(i),typ,strict=bool(i%2)) for i in ids}
            if count==64:
                with self.assertRaisesRegex(planner.PlanningError,'capture count exceeds 64'):
                    engine.recursive_captures(evidence,set(ids),{},owners,{})
            else:
                carried,saved=engine.recursive_captures(evidence,set(ids),{},owners,{})
                self.assertEqual(saved,{})
                self.assertTrue(all(carried[i] is owners[i] for i in ids))

    def test_resource_checker_rejects_wrong_full_type_and_upward_support(self):
        result=self.checked(fixture());knot,carrier,_=c.target(result)
        capture,=[x for x in carrier['mono_captures'] if x['binder']==31]
        for kind in ('type','support'):
            bad=copy.deepcopy(result['program']);contract=bad['functions'][carrier['ir_code']]['captures'][capture['capture']]
            if kind=='type':contract['layout']='^'+knot['logical_type']
            else:contract['relation']='below'
            with self.assertRaises(ResourceError):check_resources(bad)
            with self.assertRaises(ResourceError):check_metadata(bad)


