{-# LANGUAGE StandaloneDeriving, FlexibleInstances, OverloadedStrings #-}
-- Build-time lossless constructor serialization, never a source translator.
-- The consumer admits this raw data only through normal semantic checks.
module Main where
import qualified Bootstrap.Types as T
import qualified Bootstrap.CrateArtifact as A
import qualified Bootstrap.Separate as O
import qualified Bootstrap.Module as M
import qualified MLF.Host.Base as B
import Data.List (intercalate)

instance Show B.String where showsPrec n value = showsPrec n (B.unpack value)
deriving instance Show a => Show (T.Maybe a)
deriving instance Show T.Kind
deriving instance Show T.Flag
deriving instance Show T.Primitive
deriving instance Show T.Field
deriving instance Show T.ConstructorDecl
deriving instance Show T.DataDecl
deriving instance Show T.SType
deriving instance Show T.SAnnotation
deriving instance Show T.RecursiveMode
deriving instance Show T.SourceSpan
deriving instance Show T.SExpr
deriving instance Show T.SourceString
deriving instance Show T.SPattern
deriving instance Show T.SAlternative
deriving instance Show T.SStatement
deriving instance Show T.SPredicate
deriving instance Show T.SClassDecl
deriving instance Show T.SInstanceDecl
deriving instance Show T.EvidenceRole
deriving instance Show T.XTyVar
deriving instance Show T.XName
deriving instance Show T.XType
deriving instance Show T.XComputation
deriving instance Show T.XTerm
deriving instance Show T.XPattern
deriving instance Show T.XAlternative
deriving instance Show M.Role
deriving instance Show M.Entity
deriving instance Show A.CrateInterface
deriving instance Show O.UnitInterface

fragment object = "UnitObject (" ++ show (O.objectInterface object) ++ ") (" ++
  show (O.objectTerm object) ++ ")"

main = case A.builtinPrelude of
  T.Left message -> fail (B.unpack message)
  T.Right object -> do
    putStrLn "-- Generated by current Artifact.builtinPrelude; RAW data, checked by every consumer."
    putStrLn "{-# LANGUAGE NoImplicitPrelude, OverloadedStrings #-}"
    putStrLn "{-# OPTIONS_GHC -O0 #-}"
    putStrLn "module Bootstrap.PreparedBuiltinData where {"
    putStrLn "import MLF.Primitive; import Bootstrap.Types;"
    putStrLn "import Bootstrap.CrateArtifact (CrateObject(..), CrateInterface(..));"
    putStrLn "import Bootstrap.Separate (UnitObject(..), UnitInterface(..));"
    putStrLn "import Bootstrap.Module (Role(..), Entity(..));"
    putStrLn "builtin :: CrateObject;"
    putStrLn ("builtin = CrateObject (" ++ show (A.objectInterface object) ++ ") [" ++
      intercalate "," (map fragment (A.objectFragments object)) ++ "] }")
