-- mlf:syntax shared-haskell-v1
{-# LANGUAGE NoImplicitPrelude, NoMonomorphismRestriction, RankNTypes,
             KindSignatures, FlexibleContexts, FlexibleInstances,
             MultiParamTypeClasses, OverloadedStrings #-}
module MLF.Entry.BuiltinPrelude where {
  import MLF.Primitive;
  import Bootstrap.Types;
  import Bootstrap.Std (fst, snd);
  import qualified Bootstrap.BuiltinPreludeContext as Context;
  import qualified Bootstrap.CrateArtifact as Artifact;
  import qualified Bootstrap.BuiltinPreludeLiteral as Literal;

  -- This entry imports no generated data. A build orchestrator supplies the
  -- exact nongenerated source identity and saves this deterministic output.
  source identity = case (do {
    object <- Artifact.builtinPrelude; raw <- Context.prepareObject identity object;
    Right ((,) object raw)
  }) of {
    Left message -> ioReturn (Left message);
    Right ((,) object raw) -> do {
      images <- Literal.imageTexts object;
      ioReturn (do { pair <- images; Right (renderSource raw object pair) })
    }
  };
  renderSource raw object ((,) interfaceImage objectImage) =
    let { pieces = Literal.rawPreludePieces raw } in
    concatStringList
      ["-- mlf:syntax shared-haskell-v1\n",
       "-- Generated by MLF.Entry.BuiltinPrelude from the ordinary checked pipeline.\n",
       "{-# LANGUAGE NoImplicitPrelude, NoMonomorphismRestriction, RankNTypes,\n",
       "             KindSignatures, FlexibleContexts, FlexibleInstances,\n",
       "             MultiParamTypeClasses, OverloadedStrings #-}\n",
       "module MLF.BuiltinPreludeData (builtin, builtinObject, interfaceImage, objectImage) where {\n",
       "  import MLF.Primitive; import Bootstrap.Types;\n",
       "  import Bootstrap.CrateArtifact (CrateInterface(..));\n",
       "  import Bootstrap.Module (Role(..), Entity(..), ModuleSpace(..), Interface(..), Names(..));\n",
       "  import Bootstrap.SourceInference (SourceContract(..));\n",
       "  import Bootstrap.BuiltinPreludeContext (RawPrelude(..));\n",
       "  builtin :: RawPrelude;\n  builtin = ", snd pieces, ";\n", fst pieces,
       "\n  builtinObject :: String;\n  builtinObject = ",
       Literal.objectLiteral (Artifact.encodeObject object),
       ";\n  interfaceImage :: String;\n  interfaceImage = ", Literal.objectLiteral interfaceImage,
       ";\n  objectImage :: String;\n  objectImage = ", Literal.objectLiteral objectImage, "\n}\n"];
  main = do {
    count <- getArgCount;
    if count == 1 then do {
      identity <- getArg 0;
      generated <- source identity;
      case generated of {
        Left message -> do { putErr (message ++ "\n"); exitWith 1 };
        Right output -> putStr output
      }
    } else do { putErr "expected the exact nongenerated source identity\n"; exitWith 1 }
  }
}
